import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
const require = createRequire(import.meta.url);
const result = spawnSync(process.execPath, [require.resolve('typescript/lib/tsc.js')], { stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status || 1);
const web = spawnSync(process.execPath, [require.resolve('typescript/lib/tsc.js'), '-p', 'tsconfig.web.json'], { stdio: 'inherit' });
if (web.status !== 0) process.exit(web.status || 1);
const vite = spawnSync(process.execPath, ['node_modules/vite/bin/vite.js', 'build'], { stdio: 'inherit' });
if (vite.status !== 0) process.exit(vite.status || 1);
console.log('Built local server and browser app.');
