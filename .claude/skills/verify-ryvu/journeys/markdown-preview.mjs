export default async function (ctx) {
  const { page } = ctx;
  const requested = process.env.VERIFY_MARKDOWN_PR;
  if (requested) await page.waitForSelector('a.pull-row:not(.skeleton), .empty', { timeout: 60_000 });
  const candidates = requested ? [{ repo: requested.split('/').slice(0, -1).join('/'), number: Number(requested.split('/').at(-1)) }] : (await ctx.inbox()).sort((a, b) => Number(/docs|rfc/i.test(b.title)) - Number(/docs|rfc/i.test(a.title))).slice(0, 10);
  let fixture;
  for (const pull of candidates) {
    const files = ctx.github(`repos/${pull.repo}/pulls/${pull.number}/files?per_page=100`);
    const file = files.find(file => /\.(md|markdown|mdown|mkd)$/i.test(file.filename) && file.status !== 'removed' && /```mermaid/.test(file.patch ?? '') && /```(?:json|javascript|typescript|js|ts|go|python|yaml|bash)\b/.test(file.patch ?? ''));
    if (!file) continue;
    const info = ctx.github(`repos/${pull.repo}/pulls/${pull.number}`)[0];
    const blob = ctx.github(`repos/${pull.repo}/contents/${file.filename}?ref=${info.head.sha}`)[0];
    const otherPatches = files.filter(other => other.filename !== file.filename).map(other => other.patch ?? '').join('\n').toLowerCase();
    const term = (file.patch ?? '').split('\n').filter(line => line.startsWith('+') && !line.startsWith('+++')).map(line => line.slice(1).trim()).find(line => line.length > 12 && line.length < 100 && !otherPatches.includes(line.toLowerCase()));
    fixture = { ...pull, path: file.filename, text: Buffer.from(blob.content, 'base64').toString('utf8'), term };
    break;
  }
  ctx.check(Boolean(fixture), 'a real PR has a Markdown file with Mermaid and highlighted code fences');
  const { repo, number, path, text, term } = fixture;
  const fences = [...text.matchAll(/^```([^\s]*)[^\n]*\n([\s\S]*?)^```/gm)];
  const diagrams = fences.filter(match => match[1] === 'mermaid');
  const code = fences.find(match => /^(json|javascript|typescript|js|ts|go|python|yaml|bash)$/.test(match[1]));
  const heading = text.match(/^# (.+)$/m)?.[1];
  ctx.check(diagrams.length > 0 && Boolean(code) && Boolean(heading), 'GitHub supplies a heading, Mermaid diagrams and a code example');
  ctx.note(`previewing ${repo}#${number}: ${path}`);
  await ctx.go(`/pr/${repo}/${number}/diff`);
  await ctx.waitForDiffRows();
  const card = page.locator(`[id="file-${encodeURIComponent(path).replace(/%/g, '_')}"]`);
  const toggle = card.locator('button[aria-pressed]');
  const preview = card.getByRole('button', { name: 'Preview Markdown', exact: true }), diff = card.getByRole('button', { name: 'Show diff', exact: true });
  await preview.click();
  await card.getByRole('heading', { name: heading, exact: true }).waitFor({ timeout: 60_000 });
  ctx.check(await toggle.getAttribute('aria-pressed') === 'true', 'Preview selects the rendered Markdown view');
  await page.waitForFunction(({ count, path }) => {
    const card = [...document.querySelectorAll('.diff-card')].find(card => card.querySelector('.file-toggle')?.getAttribute('aria-label')?.endsWith(path));
    return card?.querySelectorAll('.mermaid-diagram svg').length === count;
  }, { count: diagrams.length, path }, { timeout: 60_000 });
  const diagram = card.locator('.mermaid-diagram svg').first();
  const box = await diagram.boundingBox();
  ctx.check(box?.width > 0 && box?.height > 0, `${diagrams.length} Mermaid diagrams draw visible SVG content`);
  const label = diagrams[0][2].match(/\[([^\]]+)\]/)?.[1].replace(/^"|"$/g, '');
  if (label) ctx.check((await diagram.textContent()).replace(/\s+/g, '').includes(label.replace(/\s+/g, '')), `the diagram draws its GitHub label "${label}"`);
  await diagram.scrollIntoViewIfNeeded(); await ctx.shot('diagram-light');
  const highlighted = card.locator('.highlighted-code').filter({ hasText: code[2].trim().slice(0, 40) }).first();
  await highlighted.waitFor({ timeout: 60_000 });
  ctx.check((await highlighted.textContent()).trim() === code[2].trim(), 'the highlighted code preserves the complete GitHub fence contents');
  const colors = () => highlighted.locator('span[style]').evaluateAll(nodes => [...new Set(nodes.map(node => getComputedStyle(node).color))]);
  const light = await colors();
  ctx.check(light.length > 1, `code uses ${light.length} syntax colors`);
  await highlighted.scrollIntoViewIfNeeded(); await ctx.shot('code-light');
  const oldId = await diagram.getAttribute('id');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(oldId => !document.getElementById(oldId), oldId);
  await diagram.waitFor({ timeout: 60_000 });
  ctx.check(await diagram.getAttribute('id') !== oldId, 'Mermaid redraws when the system theme changes');
  const dark = await colors();
  ctx.check(JSON.stringify(light) !== JSON.stringify(dark), 'syntax highlighting follows dark mode');
  await highlighted.scrollIntoViewIfNeeded(); await ctx.shot('code-dark');
  await diagram.scrollIntoViewIfNeeded(); await ctx.shot('diagram-dark');

  await diff.click();
  await preview.and(page.locator('[aria-pressed="false"]')).waitFor();
  await page.waitForFunction(path => {
    const card = [...document.querySelectorAll('.diff-card')].find(card => card.querySelector('.file-toggle')?.getAttribute('aria-label')?.endsWith(path));
    const root = card?.querySelector('diffs-container'), box = root?.getBoundingClientRect();
    return box && box.height > 0 && box.top < innerHeight && box.bottom > 0 && root.shadowRoot?.querySelector('[data-line]');
  }, path);
  ctx.check(await toggle.getAttribute('aria-pressed') === 'false' && await ctx.visibleRows() > 0, 'Diff restores drawn code rows');
  const line = card.locator('[data-line-type="change-addition"]').first();
  await line.hover(); await card.locator('[data-utility-button]').first().click();
  const draft = `verify-ryvu Markdown preview ${Date.now()}`, composer = page.getByPlaceholder('Leave a comment');
  await composer.fill(draft);
  await preview.click(); await card.locator('.markdown-file-preview h1').waitFor();
  await diff.click(); await composer.waitFor();
  ctx.check(await composer.inputValue() === draft, 'switching to Preview and back preserves an unsent comment');
  await card.getByRole('button', { name: 'Add to review', exact: true }).click();
  await card.locator('.thread', { hasText: draft }).waitFor();
  await preview.click(); await card.locator('.markdown-file-preview h1').waitFor();
  await page.getByRole('button', { name: 'Review', exact: true }).click();
  await page.getByRole('button', { name: /^\d+ pending comments?$/ }).click();
  await card.locator('.thread', { hasText: draft }).waitFor();
  ctx.check(await toggle.getAttribute('aria-pressed') === 'false', 'jumping to a comment exits Preview and shows its diff');
  await card.locator('.thread', { hasText: draft }).getByRole('button', { name: 'Delete comment' }).click();
  await card.locator('.thread', { hasText: draft }).waitFor({ state: 'detached' });
  await preview.click(); await card.locator('.markdown-file-preview h1').waitFor();
  ctx.check(Boolean(term), 'GitHub supplies a changed line unique to this file for diff search');
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+f' : 'Control+f');
  await page.getByLabel('Find in diff').fill(term);
  await page.waitForFunction(() => Boolean(CSS.highlights?.get('pr-find-current')?.size), null, { timeout: 15_000 });
  ctx.check(await toggle.getAttribute('aria-pressed') === 'false', 'finding a changed line exits Preview and draws the match');
  await page.getByLabel('Find in diff').press('Escape');
  await ctx.shot('back-to-diff');
  ctx.check(await card.locator('.mermaid-error').count() === 0, 'the real file has no diagram rendering errors');
  let failed = false;
  const outage = route => {
    if (!failed && route.request().method() === 'GET') { failed = true; return route.abort('failed'); }
    return route.continue();
  };
  await page.route('**/_serverFn/**', outage);
  await preview.click();
  await card.getByRole('alert').filter({ hasText: 'Could not load this Markdown file' }).waitFor();
  ctx.check(failed, 'a failed file request shows a recoverable preview error');
  await card.getByRole('button', { name: 'Retry', exact: true }).click();
  await card.getByRole('heading', { name: heading, exact: true }).waitFor();
  ctx.check(await toggle.getAttribute('aria-pressed') === 'true', 'Retry loads the real Markdown file successfully');
  await page.unroute('**/_serverFn/**', outage);
  await card.getByRole('button', { name: `Collapse ${path}`, exact: true }).click();
  await card.locator('.diff-card-body').waitFor({ state: 'detached' });
  await card.getByRole('button', { name: `Expand ${path}`, exact: true }).click();
  await card.getByRole('heading', { name: heading, exact: true }).waitFor();
  ctx.check(await toggle.getAttribute('aria-pressed') === 'true', 'collapsing and reopening the file keeps Preview selected');
  await page.setViewportSize({ width: 640, height: 900 });
  const control = await toggle.boundingBox();
  ctx.check(control && control.x >= 0 && control.x + control.width <= 640, 'the Preview control fits a narrow viewport');
  await ctx.shot('narrow-preview');
}
